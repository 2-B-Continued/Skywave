def region_of(cc):
    """The regions.py entry for a country code, or "" for an unknown code."""
    return REGION_OF.get(str(cc or "").upper(), "")


def single_country(rid):
    """The one country an entry stands for, or "" when several share it."""
    m = MEMBERS.get(rid, [])
    return m[0] if len(m) == 1 else ""
